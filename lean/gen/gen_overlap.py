"""Generate overlap-lemma certificates for the Lean proof (Thrackle78/Proof/OverlapData.lean).

C8 = d0..d7 (positions 0..7), C6 = w0..w5 with w0 = d0, w1 = d1; for t = 0..3, w_{t+2} is d_{j+2} (x_t = j) or a new
vertex 8 + t (x_t = None). For every assignment with distinct j's, find a class X and an injective map psi from X's
vertices into the used vertices of the union U such that every X-edge maps to a U-edge.
Classes: 0 K3, 1 C4, 2 DB681, 3 DB682, 4 DB683, 5..14 U7..U16, 15..18 u2c6_0..3.
"""
import itertools, re, sys

HYP = sys.argv[1]      # Thrackle78/Hyp.lean (listings)
GRAPHS = sys.argv[2]   # frozen graphs dir (u2c6_k.txt)
OUT = sys.argv[3]

src = open(HYP).read()
def listing(name):
    m = re.search(r'def ' + name + r' : List \(ℕ × ℕ\) :=\s*\[([^\]]*)\]', src)
    pairs = re.findall(r'\((\d+),\s*(\d+)\)', m.group(1))
    return [(int(a), int(b)) for a, b in pairs]

def gfile(name):
    L = open(f"{GRAPHS}/{name}.txt").read().split()
    n, m = int(L[0]), int(L[1])
    return n, [(int(L[2 + 2 * i]), int(L[3 + 2 * i])) for i in range(m)]

classes = []
classes.append(("K3", 3, [(0, 1), (1, 2), (2, 0)]))
classes.append(("C4", 4, [(0, 1), (1, 2), (2, 3), (3, 0)]))
for nm, n in [("lDB681", 12), ("lDB682", 11), ("lDB683", 10)]:
    classes.append((nm, n, listing(nm)))
for k, n in zip(range(7, 17), [11, 11, 10, 10, 11, 10, 10, 10, 9, 10]):
    classes.append((f"lU{k}", n, listing(f"lU{k}")))
for k in range(4):
    n, E = gfile(f"u2c6_{k}")
    classes.append((f"lu2c6_{k}", n, E))
for nm, n, E in classes:
    assert all(0 <= a < n and 0 <= b < n and a != b for a, b in E), nm
    assert len({frozenset(e) for e in E}) == len(E), nm

def union(xs):
    pos = [0, 1] + [(x + 2) if x is not None else 8 + t for t, x in enumerate(xs)]
    E = {frozenset((p, (p + 1) % 8)) for p in range(8)}
    E |= {frozenset((pos[k], pos[(k + 1) % 6])) for k in range(6)}
    used = set(range(8)) | {8 + t for t, x in enumerate(xs) if x is None}
    return used, E

def embed(n, CE, used, E):
    """injective psi : range(n) -> used with every class edge mapped to an edge of E (backtracking)."""
    adjE = {v: set() for v in used}
    for e in E:
        a, b = tuple(e)
        adjE[a].add(b); adjE[b].add(a)
    cadj = {v: set() for v in range(n)}
    for a, b in CE:
        cadj[a].add(b); cadj[b].add(a)
    order = sorted(range(n), key=lambda v: -len(cadj[v]))
    psi = {}
    def rec(i):
        if i == len(order):
            return True
        v = order[i]
        for img in used:
            if img in psi.values():
                continue
            if all(img in adjE[psi[u]] for u in cadj[v] if u in psi):
                psi[v] = img
                if rec(i + 1):
                    return True
                del psi[v]
        return False
    return [psi[v] for v in range(n)] if rec(0) else None

table = {}
stats = {}
for xs in itertools.product([None, 0, 1, 2, 3, 4, 5], repeat=4):
    js = [x for x in xs if x is not None]
    if len(js) != len(set(js)):
        continue
    used, E = union(xs)
    found = None
    for ci, (nm, n, CE) in enumerate(classes):
        psi = embed(n, CE, sorted(used), E)
        if psi is not None:
            found = (ci, psi)
            break
    assert found is not None, xs
    table[xs] = found
    stats[classes[found[0]][0]] = stats.get(classes[found[0]][0], 0) + 1
print(len(table), stats, file=sys.stderr)

def opt(x):
    return "none" if x is None else f"some {x}"

lines = []
lines.append("import Thrackle78.Proof.OverlapDefs\n")
lines.append("/-! Generated by `gen_overlap.py`: a certificate (class, vertex map) for every assignment of the overlap")
lines.append("enumeration. -/\n")
lines.append("namespace Thrackle78.Proof\n")
lines.append("/-- The certificate of an assignment (the default `(0, [])` only for assignments with repeated values). -/")
lines.append("def certOf : Option (Fin 6) → Option (Fin 6) → Option (Fin 6) → Option (Fin 6) → ℕ × List ℕ")
vals = [None, 0, 1, 2, 3, 4, 5]
for xs in itertools.product(vals, repeat=4):
    if xs in table:
        ci, psi = table[xs]
        lines.append(f"  | {opt(xs[0])}, {opt(xs[1])}, {opt(xs[2])}, {opt(xs[3])} => ({ci}, {psi})")
lines.append("  | _, _, _, _ => (0, [])\n")
lines.append("end Thrackle78.Proof")
open(OUT, "w").write("\n".join(lines) + "\n")
