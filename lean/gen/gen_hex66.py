"""Generate the 6-6 overlap certificates for the Lean proof (Thrackle78/Proof/Hex66Data.lean).

C = v0..v5 (labels 0..5), D = w0..w5 with w0 = v0; for t = 0..4, w_{t+1} is v_{x_t + 1} (x_t = j) or a new vertex
6 + t (x_t = None). For every assignment with distinct j's: certificate (99, []) if D has the same edge set as C,
else a class X and an injective map psi from X's vertices into the used labels with every X-edge an edge of the union.
Classes: 0 K3, 1 C4, 2 DB660, 3 DB661, 4 DB662, 5 DB663, 6 V4, 7 V5, 8 V7.
"""
import itertools, re, sys

HYP, OUT = sys.argv[1], sys.argv[2]
src = open(HYP).read()
def listing(name):
    m = re.search(r'def ' + name + r' : List \(ℕ × ℕ\) :=\s*\[([^\]]*)\]', src)
    return [(int(a), int(b)) for a, b in re.findall(r'\((\d+),\s*(\d+)\)', m.group(1))]

classes = [("K3", 3, [(0, 1), (1, 2), (2, 0)]), ("C4", 4, [(0, 1), (1, 2), (2, 3), (3, 0)])]
for nm, n in [("lDB660", 11), ("lDB661", 10), ("lDB662", 9), ("lDB663", 8), ("lV4", 8), ("lV5", 9), ("lV7", 10)]:
    classes.append((nm, n, listing(nm)))
for nm, n, E in classes:
    assert all(0 <= a < n and 0 <= b < n and a != b for a, b in E), nm
    assert len({frozenset(e) for e in E}) == len(E), nm

def union(xs):
    pos = [0] + [(x + 1) if x is not None else 6 + t for t, x in enumerate(xs)]
    Ce = {frozenset((p, (p + 1) % 6)) for p in range(6)}
    De = {frozenset((pos[k], pos[(k + 1) % 6])) for k in range(6)}
    used = set(range(6)) | {6 + t for t, x in enumerate(xs) if x is None}
    return used, Ce, De

def embed(n, CE, used, E):
    adjE = {v: set() for v in used}
    for e in E:
        a, b = tuple(e)
        adjE[a].add(b); adjE[b].add(a)
    cadj = {v: set() for v in range(n)}
    for a, b in CE:
        cadj[a].add(b); cadj[b].add(a)
    order = sorted(range(n), key=lambda v: -len(cadj[v]))
    psi = {}
    def rec(i):
        if i == len(order):
            return True
        v = order[i]
        for img in used:
            if img in psi.values():
                continue
            if all(img in adjE[psi[u]] for u in cadj[v] if u in psi):
                psi[v] = img
                if rec(i + 1):
                    return True
                del psi[v]
        return False
    return [psi[v] for v in range(n)] if rec(0) else None

table, stats = {}, {}
for xs in itertools.product([None, 0, 1, 2, 3, 4], repeat=5):
    js = [x for x in xs if x is not None]
    if len(js) != len(set(js)):
        continue
    used, Ce, De = union(xs)
    if Ce == De:
        table[xs] = (99, []); stats["eq"] = stats.get("eq", 0) + 1
        continue
    E = Ce | De
    found = None
    for ci, (nm, n, CE) in enumerate(classes):
        psi = embed(n, CE, sorted(used), E)
        if psi is not None:
            found = (ci, psi)
            break
    assert found is not None, xs
    table[xs] = found
    stats[classes[found[0]][0]] = stats.get(classes[found[0]][0], 0) + 1
print(len(table), stats, file=sys.stderr)

def opt(x):
    return "none" if x is None else f"some {x}"
lines = ["import Thrackle78.Proof.Hex66Defs\n",
         "/-! Generated by `gen_hex66.py`: a certificate for every assignment of the 6-6 overlap enumeration. -/\n",
         "namespace Thrackle78.Proof\n",
         "/-- The certificate of an assignment (`(99, [])`: the same 6-cycle; the default only for repeated values). -/",
         "def certOf66 : Option (Fin 5) → Option (Fin 5) → Option (Fin 5) → Option (Fin 5) → Option (Fin 5) → ℕ × List ℕ"]
for xs in itertools.product([None, 0, 1, 2, 3, 4], repeat=5):
    if xs in table:
        ci, psi = table[xs]
        lines.append(f"  | {', '.join(opt(x) for x in xs)} => ({ci}, {psi})")
lines.append("  | _, _, _, _, _ => (0, [])\n")
lines.append("end Thrackle78.Proof")
open(OUT, "w").write("\n".join(lines) + "\n")
