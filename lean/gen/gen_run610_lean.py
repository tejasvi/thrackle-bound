"""Certificates for Thrackle78/Proof/Run610Data.lean (mirrors validB610, violB, checkCert610 of Run610Defs.lean).
Kinds: 4 triangle, 5 4-cycle, 6 two 6-cycles with a common vertex and different edges, 7 a 6-cycle and an 8-cycle
with a common edge."""
import itertools, sys
from collections import Counter

def wl(xs): return [0, 1, 2, 3, 4] + list(xs)
def wlAt(xs, t): return wl(xs)[t % 10]
def cEdgeB(a, b): return a < 6 and b < 6 and (b == (a + 1) % 6 or a == (b + 1) % 6)
def sameStep(xs, t, u):
    return (wlAt(xs, t) == wlAt(xs, u) and wlAt(xs, t + 1) == wlAt(xs, u + 1)) or \
           (wlAt(xs, t) == wlAt(xs, u + 1) and wlAt(xs, t + 1) == wlAt(xs, u))
def stepMult(xs, t): return sum(1 for u in range(10) if sameStep(xs, t, u))
def validB(xs):
    if len(xs) != 5: return False
    for k in range(5):
        x = xs[k]
        if not (x < 6 or x == k + 6 or any(x == kp + 6 and xs[kp] == kp + 6 for kp in range(k))):
            return False
    return True
def violB(xs):
    if any(wlAt(xs, t) == wlAt(xs, t + 1) for t in range(10)): return True
    if any(wlAt(xs, t) == wlAt(xs, t + 2) for t in range(10)): return True
    if any(cEdgeB(wlAt(xs, t), wlAt(xs, t + 1)) and stepMult(xs, t) >= 2 for t in range(10)): return True
    if any(stepMult(xs, t) >= 3 for t in range(10)): return True
    return False
def uEdge(xs, a, b):
    return cEdgeB(a, b) or any((a == wlAt(xs, t) and b == wlAt(xs, t + 1)) or (b == wlAt(xs, t) and a == wlAt(xs, t + 1))
                               for t in range(10))
def adjOf(xs):
    labs = sorted(set(range(6)) | set(xs))
    return {a: {b for b in labs if b != a and uEdge(xs, a, b)} for a in labs}
def cycles(adj, k):
    out = []
    for s in sorted(adj):
        def rec(path):
            if len(path) == k:
                if s in adj[path[-1]] and path[1] < path[-1]:
                    out.append(list(path))
                return
            for y in sorted(adj[path[-1]]):
                if y > s and y not in path:
                    rec(path + [y])
        rec([s])
    return out
def edges(c): return {frozenset((c[i], c[(i + 1) % len(c)])) for i in range(len(c))}
def cert(xs):
    adj = adjOf(xs)
    c3 = cycles(adj, 3)
    if c3: return (4, c3[0], [])
    c4 = cycles(adj, 4)
    if c4: return (5, c4[0], [])
    c6 = cycles(adj, 6)
    for a in c6:
        for b in c6:
            if set(a) & set(b) and edges(a) != edges(b):
                return (6, a, b)
    c8 = cycles(adj, 8)
    for a in c6:
        for b in c8:
            if edges(a) & edges(b):
                return (7, a, b)
    return None

table, stats = {}, Counter()
for xs in itertools.product(range(11), repeat=5):
    if not validB(xs) or violB(xs):
        continue
    c = cert(xs)
    assert c is not None, xs
    table[xs] = c
    stats[c[0]] += 1
print(len(table), dict(stats), file=sys.stderr)
out = sys.argv[1]
lines = ["import Thrackle78.Proof.Run610Defs\n",
         "/-! Generated by `gen_run610_lean.py`: a certificate for every valid, unviolated pattern of the run lemma. -/\n",
         "namespace Thrackle78.Proof\n",
         "/-- The certificate of a pattern (the default only for invalid or violated patterns). -/",
         "def certOf610 : Fin 11 → Fin 11 → Fin 11 → Fin 11 → Fin 11 → ℕ × List ℕ × List ℕ"]
for xs in sorted(table):
    k, a, b = table[xs]
    lines.append(f"  | {', '.join(str(x) for x in xs)} => ({k}, {a}, {b})")
lines.append("  | _, _, _, _, _ => (0, [], [])\n")
lines.append("end Thrackle78.Proof")
open(out, "w").write("\n".join(lines) + "\n")
